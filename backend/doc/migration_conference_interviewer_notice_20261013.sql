--          0-待确认（默认），1-已接受，2-已拒绝。
-- 兼容：存量面试官记录的接受状态默认为 0（待确认），不影响既有逻辑。
-- 注意：字符集须为 utf8mb4_unicode_ci，与既有 t_int_* 表保持一致。
-- ============================================================================

USE recruit_agent;
SET NAMES utf8mb4;

ALTER TABLE t_int_session_interviewer
  ADD COLUMN isi_accept_status tinyint NOT NULL DEFAULT 0
  COMMENT '面试邀约接受状态：0-待确认，1-已接受，2-已拒绝';